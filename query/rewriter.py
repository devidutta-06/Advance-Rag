"""
Query rewriting via LCEL (SRS Section 15 - Query Rewriting).

The original user query is always preserved. The rewritten query is
generated by a LangChain Expression Language (LCEL) chain — a
`ChatPromptTemplate` piped through the shared `ChatOllama` and a
`StrOutputParser`. If rewriting fails, the system falls back to the
original query rather than terminating the RAG process (SRS NFR-06 -
Reliability).
"""

from __future__ import annotations

from dataclasses import dataclass

from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import Runnable, RunnableLambda

from generation.ollama_client import get_llm
from utils.logger import get_logger

logger = get_logger(__name__)

_SYSTEM_PROMPT = (
    "You rewrite short, ambiguous, or poorly formulated user questions into "
    "clear, specific, standalone questions suitable for searching a document. "
    "Preserve the original intent. Respond with ONLY the rewritten question, "
    "no explanation, no quotes."
)

_PROMPT = ChatPromptTemplate.from_messages(
    [
        ("system", _SYSTEM_PROMPT),
        ("human", "{query}"),
    ]
)


class QueryRewriteError(Exception):
    """Raised when the rewriter chain returns an empty or unusable response."""


def _strip_quotes(text: str) -> str:
    return text.strip().strip('"').strip()


@dataclass
class RewriteResult:
    original_query: str
    rewritten_query: str
    used_fallback: bool


def _build_chain() -> Runnable:
    """Compose the LCEL chain: prompt -> LLM -> string parser."""
    return _PROMPT | get_llm() | StrOutputParser() | RunnableLambda(_strip_quotes)


_chain: Runnable | None = None


def get_rewriter_chain() -> Runnable:
    """Lazy initializer for the LCEL rewriting chain."""
    global _chain
    if _chain is None:
        _chain = _build_chain()
    return _chain


def rewrite_query(original_query: str) -> RewriteResult:
    logger.info("Query rewriting started")
    logger.debug("Original query: %s", original_query)

    try:
        rewritten = get_rewriter_chain().invoke({"query": original_query})
        rewritten = (rewritten or "").strip()
        if not rewritten:
            raise QueryRewriteError("Empty rewrite response")
        logger.info("Rewritten query: %s", rewritten)
        return RewriteResult(
            original_query=original_query,
            rewritten_query=rewritten,
            used_fallback=False,
        )
    except QueryRewriteError as exc:
        logger.warning(
            "Query rewriting failed, falling back to original query: %s", exc
        )
        return RewriteResult(
            original_query=original_query,
            rewritten_query=original_query,
            used_fallback=True,
        )
